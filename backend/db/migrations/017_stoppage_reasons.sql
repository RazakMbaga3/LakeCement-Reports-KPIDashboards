-- 017: the governed stoppage REASON CATALOGUE.
--
-- Why this exists: the stoppage entry form used to take the cause of a
-- stoppage as free text, so the same fault arrived spelled a dozen ways
-- ("BE1 trip", "631BE1 tripped", "elevator tripped") and nothing could be
-- counted. The plant's own monthly "Stoppage report" workbook has always
-- had the answer -- a fixed, pre-printed list of named faults per section,
-- grouped by cause, where the shift only fills in hours against the line
-- that happened. This table is that list, so the form can present the same
-- fixed rows instead of an empty text box.
--
-- Seeded verbatim (417 rows) from "3. Stoppage report 21.04.2026 (1).xlsx"
-- using the SAME parse doctrine as scripts/import-stoppage-facts.js:
-- category order is POSITIONAL (mech, ei, prod, Common, other) because the
-- header text varies per sheet -- Cement Mill -1's own "Others" header is
-- literally the number 3 -- and "Common" is split by keyword into the
-- planned/power causes. Trailing CRITICAL/MEDIUM/Under Control severity
-- bands are not causes and are excluded.
--
-- `label` pairs with stoppage_facts.fault_description (same VARCHAR(300)),
-- which is what reliability.html's named-fault Pareto already groups on --
-- so form entries and the historical Excel imports land in one vocabulary.
CREATE TABLE IF NOT EXISTS stoppage_reasons (
  id          SERIAL PRIMARY KEY,
  equipment   VARCHAR(20)  NOT NULL,  -- STOP_EQUIPMENT key: crusher|rm|cm_coal|kiln|cm1|cm2|packing
  cause       VARCHAR(20)  NOT NULL,  -- STOP_CAUSES key: mech|ei|prod|planned|power|other
  label       VARCHAR(300) NOT NULL,  -- shown to the user; matches stoppage_facts.fault_description
  sort_order  INTEGER      NOT NULL DEFAULT 0,  -- workbook row order, so the form reads like the sheet
  -- Retiring a reason hides it from new entry without orphaning the
  -- stoppage_facts rows already recorded against its label.
  is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
  created_by  INTEGER REFERENCES users(id),  -- NULL = seeded from the workbook
  created_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
  UNIQUE (equipment, cause, label)
);

CREATE INDEX IF NOT EXISTS idx_stoppage_reasons_equip
  ON stoppage_reasons(equipment, cause, sort_order);

