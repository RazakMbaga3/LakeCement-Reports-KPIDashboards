/*
  scripts/generate-kpi-reference.js — regenerate docs/KPI_REFERENCE.md
  from forms/formula-registry.js (the single source of truth).
  Usage: npm run docs:kpi

  Output is deterministic (no timestamps): rerunning without registry
  changes produces a byte-identical file, so `git diff` on the reference
  shows only real KPI changes. Run it whenever the registry changes and
  commit both files together.
*/

const fs = require('fs');
const path = require('path');
const { FACTS, FORMULAS, REGISTRY_VERSION } = require('../../forms/formula-registry.js');

const OUT = path.join(__dirname, '..', '..', 'docs', 'KPI_REFERENCE.md');

/* ── helpers ──────────────────────────────────────────────────────── */

function mdEscape(s) { return String(s).replace(/\|/g, '\\|'); }

/* "cao_h1, cao_h2, … cao_h18" → "cao_h1 … cao_h18" for runs of ≥5
   consecutive numeric suffixes on the same prefix; everything else
   passes through untouched. */
function collapseKeys(keys) {
  const out = [];
  let i = 0;
  while (i < keys.length) {
    const m = /^(.*?)(\d+)$/.exec(keys[i]);
    if (m) {
      let j = i;
      while (
        j + 1 < keys.length &&
        keys[j + 1] === m[1] + (Number(/(\d+)$/.exec(keys[j])[1]) + 1)
      ) j++;
      if (j - i + 1 >= 5) {
        out.push(`${keys[i]} … ${keys[j]}`);
        i = j + 1;
        continue;
      }
    }
    out.push(keys[i]);
    i++;
  }
  return out;
}

function targetLine(f) {
  if (f.target !== null && f.target !== undefined) {
    const sign = f.signage === '<' ? 'below' : f.signage === '>=' ? 'at or above' : 'at';
    return `${f.targetLabel || f.target} — good is ${sign} ${f.target} ${f.unit}`;
  }
  if (f.signage === '<') return 'No fixed target — lower is better';
  if (f.signage === '>=') return 'No fixed target — higher is better';
  return 'Tracking only — no target';
}

function monthlyLine(f) {
  if (f.monthlyAgg === 'avg') {
    return 'Average of the days that have a value (missing days are excluded, not counted as zero).';
  }
  if (f.monthlyAgg === 'sum') {
    return 'Sum across the days that have a value.';
  }
  if (f.monthlyAgg && f.monthlyAgg.type === 'weighted') {
    return 'Weighted average — Σ(daily value × weight) ÷ Σ(weight), where each day\'s weight is:\n\n```js\n' +
      f.monthlyAgg.weight.toString() + '\n```';
  }
  return String(f.monthlyAgg);
}

function inputsBlock(f) {
  // group the formula's input fact keys by source form, in FACTS order
  const byForm = new Map();
  for (const key of f.inputs) {
    const fact = FACTS[key];
    const form = fact ? fact.form : '(unknown)';
    if (!byForm.has(form)) byForm.set(form, []);
    byForm.get(form).push(key);
  }
  const lines = [];
  for (const [form, keys] of byForm) {
    const entries = collapseKeys(keys).map(entry => {
      const fact = FACTS[entry.split(' ')[0]];
      return fact ? `${entry} (${fact.unit})` : entry;
    });
    lines.push(`- **${form} form:** ${entries.join(', ')}`);
  }
  return lines.join('\n');
}

/* ── document ─────────────────────────────────────────────────────── */

const kpis = Object.entries(FORMULAS);
const facts = Object.entries(FACTS);

let md = `# KPI Reference — Lake Cement MIS (Nyati Dashboard)

> **AUTO-GENERATED — do not edit this file by hand.**
> Source of truth: [\`forms/formula-registry.js\`](../forms/formula-registry.js)
> (registry version ${REGISTRY_VERSION}). To change a definition, edit the
> registry, bump the formula's \`version\`, then regenerate with
> \`npm run docs:kpi\` (in \`backend/\`) and commit both files together.

This document defines every KPI the dashboards, MIS reports, and morning
digest display: **${kpis.length} KPIs** computed from **${facts.length} raw facts**.

## How a number gets onto a dashboard

1. Departments submit daily forms; each field is a **fact** (appendix below).
2. The **daily formula** combines that day's facts into the KPI value.
   Missing inputs generally make the value *no data* — never a fake zero.
3. The **monthly roll-up** combines daily values (average, sum, or
   production-weighted average, stated per KPI below).
4. All evaluation happens server-side in one engine
   (\`backend/services/formulaEngine.js\`); every page renders the same
   \`/api/formula\` output. The browser carries the identical functions only
   for the offline/demo fallback, so the math cannot diverge.
5. An authorised manual **override** (admin/MD, reason mandatory) replaces a
   computed value but never erases it — overridden cells are flagged ⚑ on
   dashboards and in the MIS report with who/when/why.

Each fact declares one source: \`manual\` (typed into a form) today, to be
flipped per-fact to \`odoo\` when a department's Odoo feed goes live —
formulas do not change when that happens.

## KPI summary

| KPI | Unit | Target | Monthly roll-up | Version |
|---|---|---|---|---|
`;

for (const [slug, f] of kpis) {
  const agg = f.monthlyAgg === 'avg' ? 'Average'
    : f.monthlyAgg === 'sum' ? 'Sum'
    : 'Weighted average';
  md += `| [${mdEscape(f.label)}](#${slug}) | ${mdEscape(f.unit)} | ${mdEscape(f.targetLabel || '—')} | ${agg} | v${f.version} |\n`;
}

md += `\n---\n\n## KPI definitions\n`;

for (const [slug, f] of kpis) {
  md += `\n<a id="${slug}"></a>\n### ${f.label}\n\n`;
  md += `| | |\n|---|---|\n`;
  md += `| Unit | ${mdEscape(f.unit)} (shown to ${f.dp} decimal place${f.dp === 1 ? '' : 's'}) |\n`;
  md += `| Target | ${mdEscape(targetLine(f))} |\n`;
  md += `| Formula version | v${f.version} |\n`;
  md += `| Registry key | \`${slug}\` |\n\n`;
  if (f.notes) md += `${f.notes}\n\n`;
  md += `**Inputs**\n\n${inputsBlock(f)}\n\n`;
  md += `**Daily calculation** (the exact code the engine runs)\n\n`;
  md += '```js\n' + f.daily.toString() + '\n```\n\n';
  md += `**Monthly roll-up.** ${monthlyLine(f)}\n`;
}

md += `\n---\n\n## Appendix — raw facts by source form

Every field a formula can reference. *Source* is where the value comes
from today (\`manual\` = typed on the form; a fact flips to \`odoo\` when
that feed goes live).
`;

const factsByForm = new Map();
for (const [key, fact] of facts) {
  if (!factsByForm.has(fact.form)) factsByForm.set(fact.form, []);
  factsByForm.get(fact.form).push([key, fact]);
}

for (const [form, rows] of factsByForm) {
  md += `\n### ${form} form (${rows.length} fact${rows.length === 1 ? '' : 's'})\n\n`;
  md += `| Fact key | Unit | Source |\n|---|---|---|\n`;

  // collapse long numeric runs (e.g. the 18 CaO holes) into one row
  const keys = rows.map(r => r[0]);
  const collapsed = collapseKeys(keys);
  for (const entry of collapsed) {
    const firstKey = entry.split(' ')[0];
    const fact = FACTS[firstKey];
    md += `| \`${entry}\` | ${mdEscape(fact.unit)} | ${fact.source} |\n`;
  }
}

fs.writeFileSync(OUT, md, 'utf8');
console.log(`✅ Wrote ${path.relative(process.cwd(), OUT)} — ${kpis.length} KPIs, ${facts.length} facts (registry v${REGISTRY_VERSION}).`);
